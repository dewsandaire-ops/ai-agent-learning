# 10. SEARCH FAQ
# ============================================================

def search_dews_aire_faq(customer_question):

    question = normalise_dews_aire_text(customer_question)

    if not question:

        return (
            "Please provide your question so I can find the "
            "most relevant Dews & Aire FAQ."
        )

    best_match = None
    best_score = 0

    stop_words = {
        "what",
        "how",
        "can",
        "could",
        "do",
        "does",
        "did",
        "is",
        "are",
        "the",
        "a",
        "an",
        "my",
        "me",
        "you",
        "your",
        "i",
        "we",
        "our",
        "to",
        "for",
        "and",
        "of",
        "in",
        "on",
        "with",
        "please",
        "tell",
        "about",
    }

    customer_words = {
        word.strip(".,?!:;()[]{}")
        for word in question.split()
        if word not in stop_words and len(word) > 2
    }

    for category, faqs in DEWS_AIRE_FAQS.items():

        for faq in faqs:

            faq_question = normalise_dews_aire_text(
                faq["question"]
            )

            faq_answer = normalise_dews_aire_text(
                faq["answer"]
            )

            faq_text = faq_question + " " + faq_answer

            faq_words = {
                word.strip(".,?!:;()[]{}")
                for word in faq_text.split()
                if word not in stop_words and len(word) > 2
            }

            score = len(
                customer_words.intersection(faq_words)
            )

            # Give extra weight to matching words in the question.
            question_words = set(faq_question.split())

            score += len(
                customer_words.intersection(question_words)
            )

            if score > best_score:

                best_score = score
                best_match = faq

    if best_match and best_score >= 2:

        return (
            "Dews & Aire FAQ\n\n"
            f"Question: {best_match['question']}\n\n"
            f"Answer: {best_match['answer']}"
        )

    return (
        "I could not find a specific answer to that question "
        "in the Dews & Aire FAQ database.\n\n"
        "Please provide a little more information about what you "
        "need, or your enquiry can be referred to a Dews & Aire "
        "team member for assistance."
    )


