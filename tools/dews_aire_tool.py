# 6. RECOMMEND DEWS & AIRE SERVICES
# ============================================================

def recommend_dews_aire_service(request):

    request_lower = request.strip().lower()

    if not request_lower:
        return (
            "Please tell me what you need help with so I can "
            "recommend the right Dews & Aire service."
        )

    recommendations = []

    for service_key, keywords in DEWS_AIRE_SERVICE_KEYWORDS.items():

        for keyword in keywords:

            if keyword in request_lower:

                if service_key not in recommendations:
                    recommendations.append(service_key)

                break

    if not recommendations:

        return (
            "I need a little more information to recommend the right "
            "Dews & Aire service. Please tell me what you need help with."
        )

    results = []

    for recommendation in recommendations:

        service_data = DEWS_AIRE_SERVICES[recommendation]

        results.append(
            f"- {service_data['name']}: "
            f"{service_data['description']}"
        )

    return (
        "Recommended Dews & Aire Service(s)\n\n"
        + "\n".join(results)
    )


