# 9. NORMALISE TEXT
# ============================================================

def normalise_dews_aire_text(text):

    replacements = {
        "short-let": "shortlet",
        "short let": "shortlet",
        "3d visualization": "3d visualisation",
        "color": "colour",
    }

    text = text.lower().strip()

    for old, new in replacements.items():
        text = text.replace(old, new)

    return text


