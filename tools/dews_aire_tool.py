def is_dews_aire_enquiry(message):

    message_lower = message.strip().lower()

    enquiry_phrases = [

        "i need",
        "i want",
        "i would like",
        "i'd like",
        "help me",
        "hire",
        "book",
        "start a project",
        "start my project",
        "my property",
        "my building",
        "my house",
        "my apartment",
        "my construction",
        "my project",
        "i have a property",
        "i have a building",
        "i have an unfinished building",
        "i want to build",
        "i want to renovate",
        "i want to construct",
        "i want to redesign",
        "i want to manage",
        "i want to book",
        "can you help me",
        "can you manage",
        "can you supervise",
        "can you design",
        "can you build",
    ]

    return any(
        phrase in message_lower
        for phrase in enquiry_phrases
    )


