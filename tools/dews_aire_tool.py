# 7. GET FAQ CATEGORY
# ============================================================

def get_dews_aire_faq_category(category):

    search_term = category.strip().lower()

    if not search_term:

        return (
            "Please specify an FAQ category such as architecture, "
            "construction, project supervision, property management, "
            "shortlet, costs, or career guidance."
        )

    for category_key, faqs in DEWS_AIRE_FAQS.items():

        category_name = (
            category_key.replace("_", " ").lower()
        )

        if (
            search_term in category_key.lower()
            or search_term in category_name
        ):

            results = []

            for faq in faqs:

                results.append(
                    f"Q: {faq['question']}\n"
                    f"A: {faq['answer']}"
                )

            return "\n\n".join(results)

    return (
        f"No FAQ category was found matching '{category}'. "
        "Please ask about architecture, interior design, "
        "construction, project supervision, project coordination, "
        "property management, short-let booking, costs, "
        "location, working with Dews & Aire, quality, "
        "or the Career Guidance Foundation."
    )


